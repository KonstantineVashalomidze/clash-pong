package com.github.konstantinevashalomidze.clashpong.sound;

import javax.sound.sampled.AudioFormat;
import javax.sound.sampled.AudioSystem;
import javax.sound.sampled.Clip;
import javax.sound.sampled.LineUnavailableException;

/**
 * @author Surly Joe surlyjoe0101_25649 - A guy from discord
 */
public class PongSoundEffects {
  public final int SAMPLE_RATE = 44100;
  public final int PADDLE_BIT = 4;
  public final int WALL_AND_MISS_BIT = 5;
  public final double PADDLE_AND_WALL_DURATION_MS = 16.67;
  public final double MISS_DURATION_MS = 242;
  public final byte MAX_VOLUME = 127;
  public final int RESET_CLK =262;

  public final Clip paddleClip, wallClip, missClip;
  public final AudioFormat format;
  public PongSoundEffects() {
    format = new AudioFormat(SAMPLE_RATE, 8, 1, true, false);

    Clip paddle, wall, miss;
    try{
      paddle = AudioSystem.getClip();
      var pdata = pongClipData(PADDLE_BIT, PADDLE_AND_WALL_DURATION_MS,  MAX_VOLUME, RESET_CLK);
      paddle.open(format, pdata, 0, pdata.length);

      miss = AudioSystem.getClip();
      var mdata = pongClipData(WALL_AND_MISS_BIT, MISS_DURATION_MS, MAX_VOLUME, RESET_CLK);
      miss.open(format, mdata, 0, mdata.length);

      wall = AudioSystem.getClip(); // use miss data, just less of it.
      int wLen = (int)(mdata.length /(MISS_DURATION_MS/PADDLE_AND_WALL_DURATION_MS));
      wall.open(format, mdata, 0, wLen);
      
    }catch(LineUnavailableException e){
      throw new RuntimeException(e);
    }
    paddleClip = paddle;
    wallClip = wall;
    missClip = miss;

  }

  public void paddleHitSound() {playClip(paddleClip);}

  public void wallHitSound() {playClip(wallClip);}

  public void missedHitSound() {playClip(missClip);}

  void playClip(Clip clip) {
    if (clip != null && clip.isOpen()) {
      clip.setFramePosition(0);
      clip.start();
    }
  }

  /// Pong's bit counter square wave generation at 15.734KHz
  ///
  /// The original Pong arcade game had a master clock of 7.159MHz.
  /// Sound was timed by the video HRESET signal (horizontal reset) based
  /// on the scanline counter, which was 455 clock cycles.
  ///
  /// 7.159MHz / 455 = 15734.065934065935Hz
  ///
  /// The bits of the counter can be used to generate a square wave
  /// at some power of two. For example, the lowest bit will change
  /// every 2 cycles, the next bit every 4 cycles, and so on.
  /// Therefore:
  /// * bit 0 changes every 2 cycles = 15734/2 = 7867Hz
  /// * bit 1 changes every 4 cycles = 15734/4 = 3933Hz
  /// * bit 2 changes every 8 cycles = 15734/8 = 1967Hz
  /// * bit 3 changes every 16 cycles = 15734/16 = 983Hz
  /// * bit 4 changes every 32 cycles = 15734/32 = 491Hz <- paddle hit sound
  /// * bit 5 changes every 64 cycles = 15734/64 = 246Hz <- wall and score sound
  /// * bit 6 changes every 128 cycles = 15734/128 = 123Hz
  /// * bit 7 changes every 256 cycles = 15734/256 = 61Hz
  ///
  /// The paddle and wall hit sounds are generated by the 4th and 5th bits
  /// of the counter.
  ///
  /// Additionally, the missed ball sound on the original game had a cycle
  /// reset that correlates to the VRESET signal (vertical reset, where
  /// the electron gun is reset to the top of the screen), which was
  /// generated after 262 HRESET pulses. The result is a bit of sawtooth effect
  /// during the missed ball sound, which is 242ms in duration. The effect is
  /// not noticeable for the shorter 16.67ms duration paddle and wall sounds.
  ///
  /// @param freqBit  The bit to use as a counter, see frequencies above
  /// @param duration Time in milliseconds
  /// @param volume   Volume of the sound (0-127)
  /// @param resetClk The clock signal to reset the counter,
  ///                 assumed to be 262 for Pong
  /// @return the generated sound data
  /// @see
  /// <a href="https://www.namelessalgorithm.com/game_audio/blog/pong/&quot;">
  ///   Pong audio hardware analysis</a>
  byte[] pongClipData(int freqBit, double duration, double volume, int resetClk) {
    final double COUNT_RATE = 7_159_000.0 / 455.0; // 15734.065934065935Hz
    int sampleCount = (int) (SAMPLE_RATE * duration / 1000);
    byte[] soundData = new byte[sampleCount];
    for (int i = 0; i < sampleCount; i++) {
      long counter = (long) (i * COUNT_RATE / SAMPLE_RATE) % resetClk;
      int bit = (int) (counter >> freqBit) & 1;
      soundData[i] = (byte) ((bit == 0 ? -1 : 1) * volume);
    }
    return soundData;
  }

}
